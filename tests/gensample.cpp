// gensample.cpp - writes a deterministic sample "release folder" for the tests, so that `make test` needs nothing
// outside this repository: gensample <dir>
//   GAME.EXE           incompressible (pseudo-random bytes behind an MZ header): the packer must store it
//   README.TXT, LICENSE.TXT, game.ini, data\A Long File Name.txt   text (CRLF)
//   art\sky.bmp, art\tiles.bmp, art\odd.bmp   24-bit uncompressed BMPs (gradient, tiles with the RGB(255,0,255)
//                      colour key, odd width with row padding): the byte-delta filters
//   sfx\tone.wav, sfx\chord.wav               16-bit PCM, mono and stereo: the sample-delta filters
//   data\levels\level1-3.lvl  structured binary; data\empty.dat  0 bytes; data\deep\a\b\c\leaf.txt  deep folders
// The same bytes on every host and every run (own LCG, no floating-point library calls, no time).
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#ifdef _WIN32
#include <direct.h>
#define MKDIR(p) _mkdir(p)
#else
#include <sys/stat.h>
#define MKDIR(p) mkdir(p, 0755)
#endif
#include "../src/s98types.h"
#include "../src/port.h"

static u32 g_rng = 98u;
static u32 rnd()
{
  g_rng = g_rng * 1103515245u + 12345u;
  return (g_rng >> 8) & 0xFFFFFF;
}

// xorshift32: full-period bytes for the incompressible file (the LCG's low bits repeat every 64 KB)
static u32 g_xs = 2463534242u;
static u32 xorshift()
{
  g_xs ^= g_xs << 13;
  g_xs ^= g_xs >> 17;
  g_xs ^= g_xs << 5;
  return g_xs;
}

static char g_root[600];
static int g_files = 0;
static u32 g_bytes = 0;

static FILE* create(const char* rel)
{
  char path[1024];
  FILE* f;
  int i;
  s98_fmt(path, sizeof(path), "%s/%s", g_root, rel);
  for (i = (int)strlen(g_root) + 1; path[i]; i++) {       // make the folders on the way
    if (path[i] == '/') {
      path[i] = 0;
      MKDIR(path);
      path[i] = '/';
    }
  }
  f = fopen(path, "wb");
  if (!f) {
    fprintf(stderr, "gensample: cannot write %s\n", path);
    exit(1);
  }
  g_files++;
  return f;
}

static void finish(FILE* f)
{
  g_bytes += (u32)ftell(f);
  if (fclose(f) != 0) {
    fprintf(stderr, "gensample: write error\n");
    exit(1);
  }
}

static void put16(FILE* f, u32 v) { fputc((int)(v & 255), f); fputc((int)((v >> 8) & 255), f); }
static void put32(FILE* f, u32 v) { put16(f, v & 0xFFFF); put16(f, v >> 16); }

// ---- text ----

static const char* const g_words[] = { "the", "installer", "copies", "every", "file", "into", "its", "folder", "and",
  "keeps", "your", "settings", "when", "you", "upgrade", "Windows", "98", "game", "level", "sound", "picture", "a",
  "small", "fast", "compressed", "setup", "with", "one", "exe", "uninstall", "removes", "it", "again", "of", "to" };

static void words(FILE* f, u32 count)
{
  u32 i, col = 0;
  for (i = 0; i < count; i++) {
    const char* w = g_words[rnd() % (sizeof(g_words) / sizeof(g_words[0]))];
    u32 n = (u32)strlen(w);
    if (col + n + 1 > 72) { fputs("\r\n", f); col = 0; }
    else if (col) { fputc(' ', f); col++; }
    fputs(w, f);
    col += n;
    if (rnd() % 11 == 0) { fputs(".\r\n\r\n", f); col = 0; }
  }
  fputs("\r\n", f);
}

static void text_files()
{
  FILE* f = create("README.TXT");
  fputs("Sample Game 1.0\r\n===============\r\n\r\n", f);
  words(f, 4000);
  finish(f);

  f = create("LICENSE.TXT");
  fputs("Sample license\r\n\r\nThis sample is generated by tests/gensample.cpp for the Setup98 tests.\r\n"
        "Do what you like with it.\r\n", f);
  finish(f);

  f = create("game.ini");
  fputs("; default settings (a Keep file)\r\n[Game]\r\nVolume=80\r\nFullscreen=1\r\nPlayer=Player One\r\n", f);
  finish(f);

  f = create("data/A Long File Name.txt");
  words(f, 300);
  finish(f);

  f = create("data/deep/a/b/c/leaf.txt");
  fputs("deep folders are created and removed again\r\n", f);
  finish(f);

  f = create("data/empty.dat");
  finish(f);
}

// ---- binary ----

static void exe_file()
{
  FILE* f = create("GAME.EXE");
  u32 i;
  fputc('M', f);
  fputc('Z', f);
  for (i = 2; i < 160000; i++) fputc((int)(xorshift() >> 24), f);
  finish(f);
}

static void level_files()
{
  int lv;
  for (lv = 1; lv <= 3; lv++) {
    char name[64];
    FILE* f;
    u32 x, y;
    s98_fmt(name, sizeof(name), "data/levels/level%d.lvl", lv);
    f = create(name);
    fputs("LVL1", f);
    put16(f, 64);
    put16(f, 48);
    for (y = 0; y < 48; y++)
      for (x = 0; x < 64; x++) {
        u32 t = (x == 0 || y == 0 || x == 63 || y == 47) ? 1 : ((x * (u32)lv + y) % 13 == 0 ? 2 : 0);
        if (rnd() % 40 == 0) t = 3 + rnd() % 4;
        put16(f, t);
      }
    finish(f);
  }
}

// ---- pictures: 24-bit bottom-up BMP ----

typedef void (*PixFn)(u32 x, u32 y, u8* rgb);

static void bmp(const char* rel, u32 w, u32 h, PixFn fn)
{
  FILE* f = create(rel);
  u32 row = (w * 3 + 3) & ~3u, x, y;
  fputs("BM", f);
  put32(f, 54 + row * h);
  put32(f, 0);
  put32(f, 54);
  put32(f, 40);
  put32(f, w);
  put32(f, h);
  put16(f, 1);
  put16(f, 24);
  put32(f, 0);
  put32(f, row * h);
  put32(f, 2835);
  put32(f, 2835);
  put32(f, 0);
  put32(f, 0);
  for (y = h; y-- > 0;) {
    for (x = 0; x < w; x++) {
      u8 c[3];
      fn(x, y, c);
      fputc(c[2], f);              // B G R
      fputc(c[1], f);
      fputc(c[0], f);
    }
    for (x = w * 3; x < row; x++) fputc(0, f);
  }
  finish(f);
}

static void pix_sky(u32 x, u32 y, u8* c)
{
  int dx = (int)x - 240, dy = (int)y - 50;
  c[0] = (u8)(40 + y / 2);
  c[1] = (u8)(80 + y / 3);
  c[2] = (u8)(200 - y / 4);
  if (dx * dx + dy * dy < 600) { c[0] = 255; c[1] = 230; c[2] = 90; }
  if (y > 150 + (x * 7 % 23)) { c[0] = 60; c[1] = (u8)(110 + (x ^ y) % 8); c[2] = 40; }
}

static void pix_tiles(u32 x, u32 y, u8* c)
{
  u32 tx = x / 32, ty = y / 32, ix = x % 32, iy = y % 32;
  if (ix < 3 || iy < 3 || ((tx + ty) & 1 && ix > 10 && ix < 22 && iy > 10 && iy < 22)) {
    c[0] = 255; c[1] = 0; c[2] = 255;              // colour key
  } else {
    c[0] = (u8)(tx * 50 + ix * 2);
    c[1] = (u8)(ty * 60 + iy * 2);
    c[2] = (u8)(120 + ((ix * iy) & 31));
  }
}

static void pix_odd(u32 x, u32 y, u8* c)
{
  c[0] = (u8)(x * 6);
  c[1] = (u8)(y * 10);
  c[2] = (u8)(rnd() & 15);
}

// ---- sounds: 16-bit PCM ----

// a triangle wave of the given period, amplitude 0..32767 (integer only: the same on every host)
static int tri(u32 t, u32 period, int amp)
{
  u32 ph = t % period;
  int v = (int)(ph < period / 2 ? ph : period - ph) * 4 * amp / (int)period - amp;
  return v;
}

static void wav(const char* rel, u32 channels, u32 frames, u32 seed)
{
  FILE* f = create(rel);
  u32 data = frames * channels * 2, t, ch;
  fputs("RIFF", f);
  put32(f, 36 + data);
  fputs("WAVEfmt ", f);
  put32(f, 16);
  put16(f, 1);
  put16(f, channels);
  put32(f, 22050);
  put32(f, 22050 * channels * 2);
  put16(f, channels * 2);
  put16(f, 16);
  fputs("data", f);
  put32(f, data);
  for (t = 0; t < frames; t++) {
    int env = (int)(frames - t) * 256 / (int)frames;            // fade out
    for (ch = 0; ch < channels; ch++) {
      int v = tri(t, 50 + seed + ch * 13, 9000) + tri(t, 67 + ch * 7, 5000) + (int)(rnd() % 600) - 300;
      v = v * env / 256;
      put16(f, (u32)(v & 0xFFFF));
    }
  }
  finish(f);
}

int main(int argc, char** argv)
{
  if (argc != 2) {
    fprintf(stderr, "usage: gensample <dir>\n");
    return 2;
  }
  s98_fmt(g_root, sizeof(g_root), "%s", argv[1]);
  MKDIR(g_root);
  text_files();
  exe_file();
  level_files();
  bmp("art/sky.bmp", 320, 200, pix_sky);
  bmp("art/tiles.bmp", 128, 128, pix_tiles);
  bmp("art/odd.bmp", 37, 23, pix_odd);
  wav("sfx/tone.wav", 1, 11025, 0);
  wav("sfx/chord.wav", 2, 8820, 9);
  printf("gensample: %d files, %u bytes in %s\n", g_files, g_bytes, g_root);
  return 0;
}
